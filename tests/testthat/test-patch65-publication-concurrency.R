# The real guards are installed in a small isolated dev schema so two sessions
# can observe them without committing the full migration. Namespace substitution
# redirects fixture references; the locking and publication code is unchanged.
test_that("publication serializes with outstanding and subsequent draft edits", {
  skip_if(Sys.getenv("AQUACACHE_PATCH65_DATABASE") != "aquacache", "dev integration opt-in required")
  skip_if_not_installed("callr")
  connect <- function() DBI::dbConnect(RPostgres::Postgres(),dbname="aquacache",host="10.250.12.154",
    port=Sys.getenv("aquacachePort","5432"),user=Sys.getenv("aquacacheAdminUser"),password=Sys.getenv("aquacacheAdminPass"),
    connect_timeout=5,options="-c statement_timeout=20000 -c lock_timeout=15000")
  con <- connect(); on.exit(DBI::dbDisconnect(con))
  identity <- DBI::dbGetQuery(con,"SELECT current_database() AS db,inet_server_addr()::TEXT AS host")
  stopifnot(identity$db=="aquacache",identity$host=="10.250.12.154/32")
  schema <- sprintf("ac_patch65_publication_%s_%s",Sys.getpid(),as.integer(Sys.time()))
  stopifnot(!DBI::dbGetQuery(con,"SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname=$1) AS present",params=list(schema))$present)
  quoted <- as.character(DBI::dbQuoteIdentifier(con,schema))
  child <- NULL
  on.exit({
    if (!is.null(child) && child$is_alive()) child$kill()
    try(DBI::dbExecute(con,"ROLLBACK"),silent=TRUE)
    DBI::dbExecute(con,paste0("DROP SCHEMA ",quoted," CASCADE"),immediate=TRUE)
  },add=TRUE,after=FALSE)
  DBI::dbExecute(con,paste0("CREATE SCHEMA ",quoted,"; GRANT ALL ON SCHEMA ",quoted," TO admin"),immediate=TRUE)
  sql <- function(statement) DBI::dbExecute(con,gsub("FIXTURE",quoted,statement,fixed=TRUE),immediate=TRUE)
  sql("CREATE TABLE FIXTURE.parameters(parameter_id INTEGER PRIMARY KEY,param_name TEXT,
    sample_fraction BOOLEAN DEFAULT FALSE,reporting_basis BOOLEAN DEFAULT FALSE,result_speciation BOOLEAN DEFAULT FALSE,
    result_target BOOLEAN DEFAULT FALSE,endpoint BOOLEAN DEFAULT FALSE,
    analysis_conditions_required_keys TEXT[] DEFAULT '{}',analysis_conditions_required_keys_by_matrix JSONB DEFAULT '{}');
    CREATE TABLE FIXTURE.reporting_bases(reporting_basis_id INTEGER PRIMARY KEY,active BOOLEAN);
    CREATE TABLE FIXTURE.result_speciations(result_speciation_id INTEGER PRIMARY KEY,active BOOLEAN);
    CREATE TABLE FIXTURE.result_targets(result_target_id INTEGER PRIMARY KEY,active BOOLEAN);
    CREATE TABLE FIXTURE.import_mapping_sets(import_mapping_set_id INTEGER PRIMARY KEY,
      import_source_id INTEGER,import_profile_id INTEGER,version INTEGER,status TEXT);
    CREATE TABLE FIXTURE.import_parameter_mappings(import_mapping_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      import_mapping_set_id INTEGER REFERENCES FIXTURE.import_mapping_sets,source_match JSONB DEFAULT '{}',
      parameter_id INTEGER REFERENCES FIXTURE.parameters,result_type INTEGER DEFAULT 2,active BOOLEAN DEFAULT TRUE,
      sample_fraction_id INTEGER,reporting_basis_id INTEGER,result_speciation_id INTEGER,result_target_id INTEGER,
      matrix_state_id INTEGER,endpoint_mode TEXT,endpoint_ph NUMERIC,analysis_conditions JSONB DEFAULT '{}',
      analysis_conditions_key TEXT);
    CREATE FUNCTION FIXTURE.get_unique_parameter_matrix_state_id(INTEGER) RETURNS INTEGER LANGUAGE sql STABLE AS 'SELECT 1';
    CREATE FUNCTION FIXTURE.required_analysis_condition_keys(INTEGER,INTEGER) RETURNS TEXT[] LANGUAGE sql STABLE AS 'SELECT ARRAY[]::TEXT[]';
    CREATE FUNCTION FIXTURE.normalize_analysis_conditions(JSONB) RETURNS JSONB LANGUAGE sql IMMUTABLE AS 'SELECT $1';
    GRANT ALL ON ALL TABLES IN SCHEMA FIXTURE TO admin;
    INSERT INTO FIXTURE.parameters(parameter_id,param_name) VALUES(1,'fixture parameter');
    INSERT INTO FIXTURE.import_mapping_sets VALUES(1,1,NULL,1,'draft')")
  source <- paste(readLines(system.file("patches","patch_65","chemistry.sql",package="AquaCache"),warn=FALSE),collapse="\n")
  start <- regexpr("CREATE FUNCTION discrete.import_parameter_mapping_error(",source,fixed=TRUE)[[1]]
  end <- regexpr("CREATE OR REPLACE FUNCTION public.enforce_parameter_import_mapping_requirements()",source,fixed=TRUE)[[1]]
  stopifnot(start>0L,end>start)
  guards <- substr(source,start,end-1L)
  guards <- gsub("\\b(discrete|public)\\b",schema,guards,perl=TRUE)
  DBI::dbExecute(con,guards,immediate=TRUE)
  sql("CREATE TRIGGER guard_import_mapping_set BEFORE INSERT OR UPDATE OR DELETE ON FIXTURE.import_mapping_sets
      FOR EACH ROW EXECUTE FUNCTION FIXTURE.guard_import_mapping_set();
    CREATE TRIGGER guard_import_mapping_row BEFORE INSERT OR UPDATE OR DELETE ON FIXTURE.import_parameter_mappings
      FOR EACH ROW EXECUTE FUNCTION FIXTURE.guard_import_mapping_row();
    INSERT INTO FIXTURE.import_parameter_mappings(import_mapping_set_id,parameter_id) VALUES(1,1)")
  start_child <- function(statement) {
    ready <- tempfile()
    process <- callr::r_bg(function(statement,ready) {
      readRenviron("C:/Users/gtdelapl/Documents/.Renviron")
      con <- DBI::dbConnect(RPostgres::Postgres(),dbname="aquacache",host="10.250.12.154",
        port=Sys.getenv("aquacachePort","5432"),user=Sys.getenv("aquacacheAdminUser"),password=Sys.getenv("aquacacheAdminPass"),
        connect_timeout=5,options="-c statement_timeout=20000 -c lock_timeout=15000")
      on.exit(DBI::dbDisconnect(con))
      writeLines(as.character(DBI::dbGetQuery(con,"SELECT pg_backend_pid() AS pid")$pid),ready)
      tryCatch({DBI::dbExecute(con,statement,immediate=TRUE); "success"},error=conditionMessage)
    },args=list(statement=gsub("FIXTURE",quoted,statement,fixed=TRUE),ready=ready),
      stdout=tempfile(),stderr=tempfile(),poll_connection=FALSE,supervise=FALSE)
    child <<- process
    deadline <- Sys.time()+15
    while(!file.exists(ready) && process$is_alive() && Sys.time()<deadline) Sys.sleep(0.1)
    stopifnot(file.exists(ready))
    pid <- as.integer(readLines(ready)); unlink(ready)
    waiting <- FALSE
    while(process$is_alive() && Sys.time()<deadline) {
      state <- DBI::dbGetQuery(con,"SELECT wait_event_type FROM pg_stat_activity WHERE pid=$1",params=list(pid))
      if(nrow(state) && identical(state$wait_event_type,"Lock")) {waiting <- TRUE; break}
      Sys.sleep(0.1)
    }
    expect_true(waiting,"The concurrent operation must wait on the mapping-set row lock")
    process
  }
  # A publisher must see a newly committed incomplete child after waiting for
  # the editor, rather than validate its earlier command snapshot.
  sql("BEGIN; INSERT INTO FIXTURE.import_parameter_mappings(import_mapping_set_id,parameter_id) VALUES(1,NULL)")
  publisher <- start_child("UPDATE FIXTURE.import_mapping_sets SET status='published' WHERE import_mapping_set_id=1")
  sql("COMMIT")
  publisher$wait(timeout=20000)
  expect_false(publisher$is_alive())
  expect_match(publisher$get_result(),"Cannot publish incomplete")
  expect_identical(DBI::dbGetQuery(con,paste0("SELECT status FROM ",quoted,".import_mapping_sets"))$status,"draft")
  sql("DELETE FROM FIXTURE.import_parameter_mappings WHERE parameter_id IS NULL")
  # An editor that starts while publication is uncommitted must re-read the
  # final published status and reject its write, including a NULL target.
  sql("BEGIN; UPDATE FIXTURE.import_mapping_sets SET status='published' WHERE import_mapping_set_id=1")
  editor <- start_child("INSERT INTO FIXTURE.import_parameter_mappings(import_mapping_set_id,parameter_id) VALUES(1,NULL)")
  sql("COMMIT")
  editor$wait(timeout=20000)
  expect_false(editor$is_alive())
  expect_match(editor$get_result(),"only be written to a draft")
  expect_equal(DBI::dbGetQuery(con,paste0("SELECT count(*)::INTEGER AS n FROM ",quoted,".import_parameter_mappings"))$n,1L)
})
